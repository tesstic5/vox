import { NextResponse, type NextRequest } from 'next/server';
import { fail, ok, publicOrigin, requireAuth, requireConfigRole } from '@/lib/server/api';
import {
  attributeSeededDiary,
  ensureDemoOwnerVerified,
  ensureFrontDesk,
  seedDemoMoney,
  seedDemoNotes,
  seedDemoPaymentLink,
  seedOrg,
  demoHistoryEnabled,
  upgradeBookingTools,
} from '@/lib/server/bootstrap';
import { seedPractice } from '@/lib/server/practice';
import { upgradeTemplatesForOrg } from '@/lib/server/templates';
import { rememberOrigin } from '@/lib/server/manage-links';
import { seedNoteTemplatesForOrg } from '@/lib/server/notes';
import { backfillClientsFromBookings } from '@/lib/server/backfill';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

/**
 * Seeds a new organisation with a working workspace — tools, assistants, numbers,
 * webhook subscription, an API key, and two weeks of calls generated by the real
 * agent runtime. Idempotent: an org that already has assistants is left alone.
 */
export async function POST(req: NextRequest) {
  const ctx = await requireAuth(req);
  if (ctx instanceof NextResponse) return ctx;
  if (ctx.auth !== 'session') return fail('FORBIDDEN', 'Workspace setup requires a signed-in person.', { requestId: ctx.requestId });
  const denied = requireConfigRole(ctx);
  if (denied) return denied;

  const origin = publicOrigin(req);
  // A workspace that has been reached at this address can link back to it. Every
  // client text is sent by a scheduler with no request to read a Host header from,
  // so the address has to be learned while somebody is actually here.
  rememberOrigin(ctx.orgId, origin);
  const withHistory = demoHistoryEnabled();
  const result = await seedOrg(ctx.orgId, origin, { history: withHistory });
  // Whether or not this org was seeded just now, make sure it can run the
  // booking flow: the tools a campaign needs, on the assistant it dials with.
  const upgrade = upgradeBookingTools(ctx.orgId);
  // A workspace seeded before the practice layer existed still gets providers,
  // services and rotas on the next bootstrap call — see PRACTICE.md §11.
  const practice = 'practice' in result
    ? result.practice
    : withHistory
      ? seedPractice(ctx.orgId)
      : { seeded: false as const, reason: 'setup_required' };
  // Wording seeded before the self-service link existed gains it here — only for
  // rows we seeded and nobody has edited (see `upgradeTemplatesForOrg`).
  const templates = upgradeTemplatesForOrg(ctx.orgId);
  // Appointments that predate the client layer get their owners now, once.
  const clients = backfillClientsFromBookings(ctx.orgId, { withDemoRecords: false });
  // And the ones that predate the practice layer get the service they were for and
  // the practitioner who did it — reports cannot answer "who earns what" from rows
  // that name nobody (P7).
  const attribution = attributeSeededDiary(ctx.orgId);
  // The notes layer (P5): templates in the workspace's own vocabulary, and — for
  // the demo workspace only — the front-desk login that makes the record-access
  // rule watchable rather than merely claimed.
  const noteTemplates = seedNoteTemplatesForOrg(ctx.orgId);
  const frontDesk = await ensureFrontDesk(ctx.orgId);
  // The seeded demo owner is verified by seed; a real signup is not, and walks
  // the six-digit code instead. See `ensureDemoOwnerVerified`.
  const ownerVerified = ensureDemoOwnerVerified(ctx.orgId);
  // Two write-ups on the appointments that have already happened: one signed, one
  // left as the agent's draft. Idempotent, and empty for a workspace with no history.
  const demoNotes = withHistory ? await seedDemoNotes(ctx.orgId) : { seeded: 0 };
  // The books (P6): visits become invoices, money arrives, a credit note corrects
  // one of them — all through the same modules the dashboard and the API use.
  const demoMoney = withHistory ? seedDemoMoney(ctx.orgId) : { seeded: 0, paymentTypes: 0 };
  const demoPaymentLink = withHistory ? await seedDemoPaymentLink(ctx.orgId, origin) : { created: false };
  return ok(
    { ...result, upgrade, practice, templates, clients, attribution, noteTemplates, frontDesk, ownerVerified, demoNotes, demoMoney, demoPaymentLink },
    { status: result.seeded ? 201 : 200 }
  );
}
